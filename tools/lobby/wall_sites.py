"""Anchor the rock wall's dressing (crystals and mushrooms) onto the actual rock surface.

Ray-marches each dressing spot onto the wall's `wallMass` surface on the GPU, using the page's own
shader functions, and rewrites the generated block between `// @wall-dressing-begin` and
`// @wall-dressing-end` in the page. Re-run after changing the wall's rock masses or the spot list.
Owner, 2026-11-01: no wall mushroom or crystal may hover off the rock.

    python tools/lobby/wall_sites.py [--page docs/art/asset-library.html]
Requires moderngl and numpy.
"""

import argparse
import re
from pathlib import Path

import moderngl
import numpy as np

# Front-view (x, y) spots in studs. Kinds: crystal, shroom (small, in clusters of three), tiny.
SPOTS = [
    ("crystal", 1.4, 1.0), ("crystal", 1.9, 0.85), ("crystal", -4.2, 6.6), ("crystal", -3.8, 6.95), ("crystal", 7.3, 3.8),
    ("shroom", -6.7, 2.0), ("shroom", -6.3, 2.4), ("shroom", -6.0, 2.0),
    ("shroom", 4.3, 5.9), ("shroom", 4.7, 6.2), ("shroom", 5.0, 5.8),
    ("shroom", -1.5, 9.3), ("shroom", -1.1, 9.6), ("shroom", -0.8, 9.3),
    ("tiny", -2.2, 4.6), ("tiny", 6.8, 1.6), ("tiny", 2.6, 7.6), ("tiny", -7.6, 8.0), ("tiny", 0.8, 3.2),
    ("tiny", -4.9, 10.2), ("tiny", -1.8, 4.8), ("tiny", 7.2, 1.7), ("tiny", 3.0, 7.8),
]

PROBE_MAIN = """
uniform vec2 uSpots[%d];
out vec4 fragColor;
void main() {
  int i = int(gl_FragCoord.x);
  int row = int(gl_FragCoord.y);
  vec2 s = uSpots[i];
  float z = -8.0, hit = 0.0;
  for (int k = 0; k < 400; k++) {
    float d = wallMass(vec3(s, z));
    if (d < 0.0005) { hit = 1.0; break; }
    z += max(d*0.6, 0.004);
    if (z > 5.0) break;
  }
  vec3 p = vec3(s, z);
  const float e = 0.01;
  vec3 n = normalize(vec3(wallMass(p + vec3(e, 0, 0)) - wallMass(p - vec3(e, 0, 0)),
                          wallMass(p + vec3(0, e, 0)) - wallMass(p - vec3(0, e, 0)),
                          wallMass(p + vec3(0, 0, e)) - wallMass(p - vec3(0, 0, e))));
  fragColor = row == 0 ? vec4(p, hit) : vec4(n, 0.0);
}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--page", default="docs/art/asset-library.html")
    args = ap.parse_args()
    path = Path(args.page)
    page = path.read_text(encoding="utf-8")
    fs = re.search(r'<script id="fs" type="x-shader/x-fragment">(.*?)</script>', page, re.S).group(1)
    prefix = fs[:fs.rindex("\nvoid main() {")]
    prefix = prefix.replace("precision highp float;", "precision highp float;\n#define ASSET 0", 1)
    src = "#version 330\n" + prefix + PROBE_MAIN % len(SPOTS)

    ctx = moderngl.create_standalone_context()
    # Probe a small grid around each spot and keep the nearest point that faces forward and is not an
    # overhang underside, so dressing never lands in a gap between rock masses or hangs upside down.
    offsets = [(dx*0.15, dy*0.15) for dx in range(-5, 6) for dy in range(-5, 6)]
    offsets.sort(key=lambda o: o[0]**2 + o[1]**2)
    batch = 200
    src = src.replace("uniform vec2 uSpots[%d];" % len(SPOTS), "uniform vec2 uSpots[%d];" % batch)
    prog = ctx.program(vertex_shader="#version 330\nin vec2 aPos; void main(){ gl_Position = vec4(aPos, 0.0, 1.0); }",
                       fragment_shader=src)
    vbo = ctx.buffer(np.array([-1, -1, 3, -1, -1, 3], dtype="f4").tobytes())
    vao = ctx.vertex_array(prog, [(vbo, "2f", "aPos")])
    fbo = ctx.framebuffer(color_attachments=[ctx.texture((batch, 2), 4, dtype="f4")])

    def probe(points):
        out = []
        for k in range(0, len(points), batch):
            chunk_pts = points[k:k + batch]
            padded = chunk_pts + [(0.0, 0.0)]*(batch - len(chunk_pts))
            prog["uSpots"].write(np.array(padded, dtype="f4").tobytes())
            fbo.use()
            vao.render()
            res = np.frombuffer(fbo.read(components=4, dtype="f4"), dtype="f4").reshape(2, batch, 4)
            out += [(res[0, j], res[1, j]) for j in range(len(chunk_pts))]
        return out

    chosen = []
    for kind, x, y in SPOTS:
        cands = [(x + dx, y + dy) for dx, dy in offsets]
        pick = None
        for (cx, cy), (p, n) in zip(cands, probe(cands)):
            if p[3] > 0.5 and n[2] < -0.55 and n[1] > -0.2 and p[2] < 0.2:
                pick = (p, n)
                break
        chosen.append(pick)

    lines = ["  // Generated by tools/lobby/wall_sites.py: each spot sits on the measured rock surface."]
    for i, (kind, x, y) in enumerate(SPOTS):
        if chosen[i] is None:
            print(f"spot {i} ({kind} at {x}, {y}): no suitable rock surface nearby; skipped")
            continue
        p, n = chosen[i]
        sv = f"vec3({p[0]:.3f}, {p[1]:.3f}, {p[2]:.3f})"
        nv = f"vec3({n[0]:.3f}, {n[1]:.3f}, {n[2]:.3f})"
        seed = f"{float(i):.1f}"
        if kind == "crystal":
            lines.append(f"  wallCrystal(p, {sv}, {nv}, {seed}, cr);")
        else:
            tiny = "1.0" if kind == "tiny" else "0.0"
            lines.append(f"  wallShroom(p, {sv}, {nv}, {seed}, {tiny}, stems, caps, capIdx);")
        print(f"spot {i:2d} {kind:7s} surface z {p[2]:6.2f}  normal {n[0]:5.2f} {n[1]:5.2f} {n[2]:5.2f}")
    block = "\n".join(lines)
    page = re.sub(r"(  // @wall-dressing-begin\n).*?(  // @wall-dressing-end)", lambda m: m.group(1) + block + "\n" + m.group(2),
                  page, count=1, flags=re.S)
    path.write_text(page, encoding="utf-8", newline="")


if __name__ == "__main__":
    main()
