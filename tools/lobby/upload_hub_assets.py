"""Upload built hub pieces privately to the owner's Roblox account (owner-approved, 2026-11-01), the same way as
tools/lobby/upload_lobby_assets.py and sharing its client and hash cache. Writes, under ignored private-assets/lobby/:
  HubAssets.luau       model and effect texture ids, and each part's place in the hub
  hub_materials.rbxmx  SurfaceAppearance templates (map setters are plugin-only, so the place clones these)

    python tools/lobby/upload_hub_assets.py [key ...]     default: every built piece
"""

import hashlib
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from upload_lobby_assets import EXPORT, PRIVATE, ROOT, load_client, upload  # noqa: E402

FX = ROOT/"build/lobby/fx"
HUB = PRIVATE/"hub_manifest.json"


def v3(p):
    return f"Vector3.new({p[0]:.3f}, {p[1]:.3f}, {p[2]:.3f})"


def main():
    keys = sys.argv[1:] or sorted(p.parent.name for p in EXPORT.glob("hub-*/build.json"))
    client = load_client()
    key = client.api_key()
    owner = json.loads((ROOT/"private-assets/floppy/roblox_assets.json").read_text())["owner"]
    cache_path = PRIVATE/"uploads.json"
    cache = json.loads(cache_path.read_text()) if cache_path.exists() else {}

    def cached(tag, path, asset_type, content_type):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if cache.get(tag, {}).get("sha256") == digest:
            return cache[tag]["id"]
        asset_id = upload(client, key, owner, path, asset_type, "Slugshot " + tag, content_type)
        cache[tag] = {"id": asset_id, "sha256": digest}
        cache_path.write_text(json.dumps(cache, indent=1))
        print(f"uploaded {tag}", flush=True)
        return asset_id

    manifest = json.loads(HUB.read_text()) if HUB.exists() else {}
    manifest = {k: e for k, e in manifest.items() if (EXPORT/k/"build.json").exists()}
    for k in keys:
        report = json.loads((EXPORT/k/"build.json").read_text())
        entry = {"model": cached(f"{k} model", EXPORT/k/f"{k}.glb", "Model", "model/gltf-binary"), "groups": {}}
        for g in report["groups"]:
            maps = {kind: cached(f"{k} {g['name']} {kind}", EXPORT/k/g[kind], "Image", "image/png")
                    for kind in ("color", "normal", "emit") if kind in g}
            entry["groups"][g["name"]] = {"maps": maps, "ink": g.get("inkShell"), "emissive": g.get("emissiveStrength", 0),
                                          "min": g["boundsMin"], "max": g["boundsMax"], "alpha": g.get("alpha", False)}
        points = ROOT/"build/lobby/meshes"/k/"points.json"
        entry["points"] = json.loads(points.read_text()) if points.exists() else []
        manifest[k] = entry
    HUB.write_text(json.dumps(manifest, indent=1))
    fx = {p.stem: cached(f"fx {p.stem}", p, "Image", "image/png") for p in sorted(FX.glob("*.png"))}

    lines = ["--!strict", "-- Private hub asset ids; never commit. Generated by tools/lobby/upload_hub_assets.py.", "return {", "\tfx = {"]
    lines += [f"\t\t{name} = {asset},"for name, asset in fx.items()]
    lines += ["\t},", "\tassets = {"]
    for k, e in manifest.items():
        points = ", ".join(f"{{ p = {v3(pt['p'])}, c = Color3.new({pt['c'][0]:.3f}, {pt['c'][1]:.3f}, {pt['c'][2]:.3f}) }}"
                           for pt in e.get("points", []))
        lines.append(f'\t\t["{k}"] = {{ model = {e["model"]}, points = {{ {points} }}, parts = {{')
        for name, g in e["groups"].items():
            ink = f'"{g["ink"]}"' if g["ink"] else "nil"
            lines.append(f'\t\t\t{name} = {{ ink = {ink}, emissive = {g["emissive"]}, min = {v3(g["min"])}, max = {v3(g["max"])} }},')
        lines.append("\t\t} },")
    lines += ["\t},", "}", ""]
    (PRIVATE/"HubAssets.luau").write_text("\n".join(lines), encoding="utf-8")

    doc = ET.Element("roblox", version="4")
    folder = ET.SubElement(doc, "Item", {"class": "Folder", "referent": "HubMaterials"})
    ET.SubElement(ET.SubElement(folder, "Properties"), "string", name="Name").text = "HubMaterials"
    for k, e in manifest.items():
        for name, g in e["groups"].items():
            item = ET.SubElement(folder, "Item", {"class": "SurfaceAppearance", "referent": f"{k}_{name}"})
            props = ET.SubElement(item, "Properties")
            ET.SubElement(props, "string", name="Name").text = f"{k}/{name}"
            if g.get("alpha"):
                ET.SubElement(props, "token", name="AlphaMode").text = "1"  # Enum.AlphaMode.Transparency
            for kind, prop in (("color", "ColorMap"), ("normal", "NormalMap")):
                if kind in g["maps"]:
                    content = ET.SubElement(props, "Content", name=prop)
                    ET.SubElement(content, "url").text = f"rbxassetid://{g['maps'][kind]}"
            if "emit" in g["maps"]:
                content = ET.SubElement(props, "Content", name="EmissiveMaskContent")
                ET.SubElement(content, "uri").text = f"rbxassetid://{g['maps']['emit']}"
    ET.ElementTree(doc).write(PRIVATE/"hub_materials.rbxmx", encoding="utf-8", xml_declaration=True)
    print("PASS: hub pieces uploaded privately:", ", ".join(keys))


if __name__ == "__main__":
    main()
