"""Traces the blaster's real side-on outline into the gateway rune, so the rune can't drift from the model.

Writes the generated `// @blaster-rune-begin` block in docs/art/asset-library.html, then repaint the gate with
`hub_mesh.py paint hub-gate-3`.

    python tools/lobby/blaster_rune.py [preview.png]
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    import bpy
except ImportError:
    bpy = None

import numpy as np

MODEL = Path("build/lobby/characters/blaster-final/model.glb")
PAGE = Path("docs/art/asset-library.html")
BLENDER = os.environ.get("BLENDER", "C:/Users/runni/slugshot/.tools/blender-5.2.3-windows-x64/blender.exe")
GRID = 900
SPAN = 1.84  # the longest side, in the symbol's -1 to 1 square
THICKEN = 5  # pixels of grid, so the trigger guard's thin line survives at keystone size
TOLERANCE = 1.6  # pixels of grid


def dump_triangles(source, target):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=source)
    graph = bpy.context.evaluated_depsgraph_get()
    tris = []
    for ob in bpy.context.scene.objects:
        if ob.type == "MESH" and "_Ink" not in ob.name:
            me = ob.evaluated_get(graph).to_mesh()
            me.calc_loop_triangles()
            co = np.array([(ob.matrix_world @ v.co)[:] for v in me.vertices], "f4")
            tris.append(co[np.array([t.vertices[:] for t in me.loop_triangles], "i4")])
    np.save(target, np.concatenate(tris))


def trace_loops(mask):
    """Every boundary between filled and empty cells, joined into closed loops, filled side on the left."""
    filled = np.pad(mask, 1)
    next_edge = {}
    for y, x in np.argwhere(filled[1:] != filled[:-1]):
        a, b = (x, y + 1), (x + 1, y + 1)
        if filled[y + 1, x]:
            a, b = b, a
        next_edge.setdefault(a, []).append(b)
    for y, x in np.argwhere(filled[:, 1:] != filled[:, :-1]):
        a, b = (x + 1, y), (x + 1, y + 1)
        if filled[y, x]:
            a, b = b, a
        next_edge.setdefault(a, []).append(b)
    loops = []
    while next_edge:
        start = next(iter(next_edge))
        loop, here = [], start
        while True:
            loop.append(here)
            ends = next_edge[here]
            there = ends.pop()
            if not ends:
                del next_edge[here]
            here = there
            if here == start:
                break
        loops.append(np.array(loop, "f8") - 1)
    return loops


def simplify(points, tolerance):
    """Douglas-Peucker on an open run of points."""
    keep = np.zeros(len(points), bool)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        if b <= a + 1:
            continue
        line = points[b] - points[a]
        length = max(np.hypot(*line), 1e-9)
        off = np.abs(np.cross(line, points[a + 1:b] - points[a]))/length
        worst = int(off.argmax())
        if off[worst] > tolerance:
            keep[a + 1 + worst] = True
            stack += [(a, a + 1 + worst), (a + 1 + worst, b)]
    return points[keep]


def simplify_loop(loop):
    far = int(np.hypot(*(loop - loop[0]).T).argmax())
    first = simplify(loop[:far + 1], TOLERANCE)
    second = simplify(np.vstack([loop[far:], loop[:1]]), TOLERANCE)
    return np.vstack([first[:-1], second[:-1]])


def main():
    from PIL import Image, ImageDraw, ImageFilter

    with tempfile.TemporaryDirectory() as folder:
        target = Path(folder)/"tris.npy"
        subprocess.run([BLENDER, "--background", "--factory-startup", "--python", __file__, "--", str(MODEL), str(target)],
                       check=True, stdout=subprocess.DEVNULL)
        tris = np.load(target)
    # Imported Z up with the muzzle along +Y, so Y runs along the gun and Z up it.
    side = tris[:, :, [1, 2]].astype("f8")
    lo, hi = side.reshape(-1, 2).min(axis=0), side.reshape(-1, 2).max(axis=0)
    scale = (GRID - 40)/(hi - lo).max()
    image = Image.new("L", (GRID, GRID), 0)
    draw = ImageDraw.Draw(image)
    middle = (lo + hi)/2
    for tri in side:
        draw.polygon([tuple(GRID/2 + (p - middle)*scale*(1, -1)) for p in tri], fill=255)
    image = image.filter(ImageFilter.MaxFilter(THICKEN))
    loops = [simplify_loop(loop) for loop in trace_loops(np.array(image) > 127)]
    loops = [loop for loop in loops if len(loop) >= 3]
    to_symbol = SPAN/(GRID - 40)
    corners = sum(len(loop) for loop in loops)
    edges = []
    for loop in loops:
        symbol = (loop - GRID/2)*to_symbol*(1, -1)
        for a, b in zip(symbol, np.roll(symbol, -1, axis=0)):
            edges += [a, b]
    values = ",".join(f"vec2({x:.3f},{y:.3f})" for x, y in edges)
    block = (
        "// @blaster-rune-begin Generated by tools/lobby/blaster_rune.py from the real blaster model; do not edit.\n"
        f"const int BLASTER_EDGES = {len(edges)//2};\n"
        f"const vec2 BLASTER_RUNE[{len(edges)}] = vec2[{len(edges)}]({values});\n"
        "float blasterRune(vec2 g) {\n"
        "  float best = 1e9, inside = 1.0;\n"
        "  for (int i = 0; i < BLASTER_EDGES; i++) {\n"
        "    vec2 a = BLASTER_RUNE[2*i], e = BLASTER_RUNE[2*i + 1] - a, w = g - a;\n"
        "    vec2 d = w - e*clamp(dot(w, e)/dot(e, e), 0.0, 1.0);\n"
        "    best = min(best, dot(d, d));\n"
        "    if ((a.y > g.y) != (a.y + e.y > g.y) && g.x < a.x + e.x*(g.y - a.y)/e.y) inside = -inside;\n"
        "  }\n"
        "  return inside*sqrt(best);\n"
        "}\n"
        "// @blaster-rune-end\n"
    )
    text = PAGE.read_text(encoding="utf-8")
    begin, end = "// @blaster-rune-begin", "// @blaster-rune-end\n"
    assert text.count(begin) == 1, "the page needs its generated block"
    a, b = text.index(begin), text.index(end) + len(end)
    PAGE.write_text(text[:a] + block + text[b:], encoding="utf-8")
    print(json.dumps({"loops": len(loops), "corners": corners, "edges": len(edges)//2}))
    if len(sys.argv) > 1:
        size = 320
        sy, sx = np.mgrid[1.1:-1.1:size*1j, -1.1:1.1:size*1j]
        inside = np.zeros(sx.shape, bool)
        for i in range(0, len(edges), 2):
            a, b = edges[i], edges[i + 1]
            if a[1] == b[1]:
                continue
            crosses = (a[1] > sy) != (b[1] > sy)
            inside ^= crosses & (sx < a[0] + (b[0] - a[0])*(sy - a[1])/(b[1] - a[1]))
        fill = inside[..., None]*np.array((255, 215, 110), "u1") + (~inside)[..., None]*np.array((26, 23, 22), "u1")
        big = Image.fromarray(fill.astype("u1"))
        sheet = Image.new("RGB", (size + 120, size), (10, 10, 10))
        sheet.paste(big, (0, 0))
        sheet.paste(big.resize((64, 64), Image.LANCZOS), (size + 28, 120))
        sheet.save(sys.argv[1])


if __name__ == "__main__":
    if bpy is not None:
        arguments = sys.argv[sys.argv.index("--") + 1:]
        dump_triangles(*arguments)
    else:
        main()
